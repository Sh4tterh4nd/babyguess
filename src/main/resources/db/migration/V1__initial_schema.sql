CREATE TABLE participant (
    id UUID PRIMARY KEY,
    display_name VARCHAR(120) NOT NULL,
    email_address VARCHAR(320) NOT NULL,
    normalized_email_address VARCHAR(320) NOT NULL UNIQUE,
    edit_token_hash CHAR(64) NOT NULL UNIQUE,
    locale VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE submission_version (
    id UUID PRIMARY KEY,
    participant_id UUID NOT NULL REFERENCES participant(id),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    predicted_sex VARCHAR(16) CHECK (predicted_sex IN ('GIRL', 'BOY')),
    predicted_birth_date DATE,
    predicted_birth_weight_grams INTEGER CHECK (predicted_birth_weight_grams > 0)
);

CREATE INDEX submission_version_participant_time_idx
    ON submission_version (participant_id, submitted_at DESC);

CREATE TABLE name_guess (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_version_id UUID NOT NULL REFERENCES submission_version(id),
    guess_position INTEGER NOT NULL CHECK (guess_position >= 1),
    guessed_name VARCHAR(160) NOT NULL,
    cosmetic_name VARCHAR(160) NOT NULL,
    UNIQUE (submission_version_id, guess_position),
    UNIQUE (submission_version_id, cosmetic_name)
);

CREATE TABLE accepted_name_variant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cosmetic_name VARCHAR(160) NOT NULL UNIQUE,
    display_name VARCHAR(160) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
